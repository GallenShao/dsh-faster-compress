import { readFile, mkdir, writeFile } from 'node:fs/promises'

// DSH supplies React and its native settings components through ModuleLoader.
// Ship this tiny browser module ready to load; installing the package runs no build.
const root = new URL('../', import.meta.url)
const source = await readFile(new URL('src/client.cjs', root), 'utf8')
const contract = await readFile(new URL('src/trace-contract.cjs', root), 'utf8')
const traceView = await readFile(new URL('src/trace-view.cjs', root), 'utf8')
const css = await readFile(new URL('src/trace.css', root), 'utf8')
const locales = Object.fromEntries(await Promise.all(['zh', 'en'].map(async language => [
  language, JSON.parse(await readFile(new URL(`locale/${language}.json`, root), 'utf8')),
])))
const bundle = `// Generated by scripts/build-client.mjs. Edit src/client.cjs, src/trace* or locale/*.json.\nwindow.__ModuleLoader__.load({\n  id: 'dsh-faster-compress',\n  factory: (require) => {\n    const module = { exports: {} }\n    const locales = ${JSON.stringify(locales, null, 2)}\n    const traceCss = ${JSON.stringify(css)}\n    const { traceDescriptor } = (() => { const module = { exports: {} };\n${contract}\nreturn module.exports })()\n    const { TraceView } = (() => { const module = { exports: {} };\n${traceView}\nreturn module.exports })()\n${source}\n    return module.exports\n  },\n})\n`
await mkdir(new URL('client/', root), { recursive: true })
await writeFile(new URL('client/index.js', root), bundle)
